#!/usr/bin/env node
/* Contract test for IA collection-to-episode depth. The test intentionally
 * exercises both clients because they must emit the same editorial rails. */
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const root = path.join(__dirname, '..');
let failures = 0;
function check(ok, message) {
  console.log(`${message}: ${ok ? 'ok' : 'FAILED'}`);
  if (!ok) failures += 1;
}

for (const file of ['the_dial_desktop.html', 'the_dial_mobile.html']) {
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  check(source.includes('IA DEPTH PASS (v2.0)'), `${file}: IA depth overlay present`);
  check(source.includes('deepCollections') && source.includes('deepTitleTerms'), `${file}: deep collection fields present`);
  check(source.includes('if(Array.isArray(prog.deepCollections)&&prog.deepCollections.length)'), `${file}: deep rails are generated by the shared query builder`);
  check(source.includes('adverts') && source.includes('station ident'), `${file}: animation lanes reject ad-break and station-ident uploads`);
}

const exported = spawnSync(process.execPath, [path.join(root, 'scripts', 'export-ia-manifest.js'), path.join(root, 'the_dial_desktop.html')], { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 });
check(exported.status === 0, 'IA manifest export succeeds after depth overlay');
let manifest = [];
try { manifest = JSON.parse(exported.stdout || '[]'); } catch (error) { check(false, `IA manifest JSON parses: ${error.message}`); }
const depthRows = manifest.filter(item => item.queries.some(query => query.includes('collection:') && query.includes('title:')));
check(depthRows.length === manifest.length, `All ${manifest.length} IA stations expose a bounded collection/title depth rail`);
const expectedRails = {
  '150': 'classic_cartoons',
  '153': 'animationandcartoons',
  '158': 'saturdaymorningcartoons',
  '10': 'classic_tv',
  '11': 'classic_tv',
  '12': 'classic_tv_1950s',
};
for (const [channel, collection] of Object.entries(expectedRails)) {
  const row = manifest.find(item => String(item.channel) === channel);
  check(Boolean(row), `IA channel ${channel} is in the exported manifest`);
  check(Boolean(row && row.queries.some(query => query.includes(`collection:${collection}`))), `IA channel ${channel} exposes ${collection} depth rail`);
}

const relay = fs.readFileSync(path.join(root, 'afterglow_ais_relay_worker.js'), 'utf8');
check(/IA_QUEUE_CACHE_VERSION\s*=\s*"v67"/.test(relay), 'Relay cache namespace is v67');
check(/"206": \[/.test(relay) && /090-aahma-watermarked/.test(relay) && /amateur_west_1940_1/.test(relay), 'Home Movies has verified sparse-lane recovery media');
check(/"12": \[/.test(relay) && /whatsmyline5September1954/.test(relay) && /Price_Is-Right_1957/.test(relay), 'Game Show Channel has a rotating verified temporary fallback shelf');
check(/"115": \[/.test(relay) && /1989gojirataibiorante/.test(relay) && /thereturnofgodzilla1984/.test(relay), 'Monster Island has verified kaiju recovery media');
check(/"154": \[/.test(relay) && /DragnetEpisode18TheBigSeventeenwcommercials/.test(relay) && /hawaii-five-o-S2E3-480p/.test(relay), 'Cop Show Classic has verified police-procedural recovery media');
check(/"157": \[/.test(relay) && /powerpuff-girls-complete-series/.test(relay) && /StarWarsCloneWars2003/.test(relay), 'After School has verified kids-animation recovery media');
check(/"228": \[/.test(relay) && /WETA_20131009_140000_Frontline/.test(relay) && /KYW_20141012_230000_60_Minutes/.test(relay), 'Deadline has verified newsmagazine recovery media');
check(/"75": \[/.test(relay) && /XcorpsNOODregattaSEG2/.test(relay) && /jseALNAIRracing94ver2/.test(relay), 'Regatta has real IA water-sports recovery media');
check(/IA_STRICT_CATALOG_CANDIDATE_MAX\s*=\s*72/.test(relay) && /IA_CATALOG_CANDIDATE_MAX\s*=\s*48/.test(relay), 'Relay retains the expanded rolling catalog budgets');
check(/candidateLimit = Math\.max\(count, Math\.min\(IA_STRICT_CATALOG_CANDIDATE_MAX/.test(relay), 'Relay builds the candidate shelf from the expanded budget');
check(/const expandedSources = new Set\(expanded\.map/.test(relay) && /const approvedPrograms = approved\.filter/.test(relay), 'Relay drops parent indexes after episode expansion');
check(/const expansionSeeds = firstApprovedLane \? \[\] : hintedSeeds\.concat\(genericSeeds\)/.test(relay), 'Relay keeps manifest expansion off the first-frame path');
check(/const expandedParents = new Set\(\)/.test(relay), 'Relay removes expanded parents across editorial rails');
check(/candidateItems: items\.slice\(0, candidateLimit\)/.test(relay), 'Relay serializes the rolling candidate shelf');
check(/const backgroundTarget = Math\.min\(candidateCount, Math\.max\(count, 15\)\)/.test(relay), 'Relay hydrates a deeper background playable shelf');
check(/function rotatePlayableIaShelf\(/.test(relay) && /rotatePlayableIaShelf\(lastGood/.test(relay), 'Relay rotates hydrated last-good shelves instead of repeating the same five items');
check(/const emergencyDepth = Math\.min\(candidateCount, Math\.max\(count, 8\)\)/.test(relay), 'Sparse emergency lanes widen before accepting a shallow five-item shelf');
check(/IA_BACKGROUND_CONTAINER_EXPANSIONS\s*=\s*4/.test(relay), 'Background collection expansion covers four parent records per lane');
check(/function orderedIaEmergencySeeds\(/.test(relay) && /emergencySeedsMerged: true/.test(relay), 'Warm emergency shelves join background depth repair');
check(/function mergeIaFallbackCandidates\(/.test(relay) && /\[\.\.\.current, \.\.\.prior\]/.test(relay), 'Last-good IA shelves accumulate verified candidates across rotations');
check(/if \(payload && payload\.lastGoodKey\)/.test(relay) && /familyCandidates = mergeIaFallbackCandidates\(family, expanded\)/.test(relay), 'Exact IA rotation refills inherit the accumulated family catalog');
check(/const cachedShelf =/.test(relay) && /const sharedShelf =/.test(relay), 'Cached and shared IA shelves rotate their deeper playable candidates');
check(/\* requested\) % source\.length/.test(relay), 'Shelf rotation advances by a full public window');

if (failures) process.exitCode = 1;
else console.log('IA collection-depth contract passed.');
